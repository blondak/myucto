-- Úplný číselník zemí podle ISO 3166-1 (249 států a území).
--
-- Do 1828 měl číselník jen EU a několik okolních států, takže převod adresáře z cizího
-- systému hlásil u partnerů z Ruska, Číny, Tchaj-wanu, Srbska a dalších „stát v číselníku
-- zemí není" a partner dostal zemi firmy.
--
-- Názvy (česky i anglicky) a kódy alpha-3 jsou vygenerované z ICU (PHP intl, ICU 77)
-- a zapsané staticky, ať migrace nezávisí na rozšíření intl.
--
-- Instalace mohou mít v číselníku země přidané ručně, s vlastními názvy i bez alpha-3.
-- Proto:
--   * nová země se vloží jen tehdy, když v tabulce není řádek se stejným iso2 ANI iso3
--     (unikátní klíč je jen na iso2, na iso3 se nezakládá, na existujících datech by
--     mohl narazit na duplicitu);
--   * existující řádek se nepřepisuje: id, názvy, iso3 ani is_eu zůstávají, doplní se
--     jen prázdné iso3 a prázdné názvy (iso3 jen tehdy, když ho nemá jiný řádek);
--   * nové země mají is_eu = 0, členské státy EU číselník obsahuje od 0001.
-- Idempotentní: opakovaný běh nic nevloží ani nezmění.

