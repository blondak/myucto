UPDATE tmp_1828_countries s
   SET s.iso3_free = NOT EXISTS (SELECT 1 FROM countries c WHERE UPPER(TRIM(c.iso3)) = s.iso3);

UPDATE countries c
  JOIN tmp_1828_countries s ON UPPER(TRIM(c.iso2)) = s.iso2
   SET c.iso3    = IF(TRIM(c.iso3) = '' AND s.iso3_free = 1, s.iso3, c.iso3),
       c.name_cs = IF(TRIM(c.name_cs) = '', s.name_cs, c.name_cs),
       c.name_en = IF(TRIM(c.name_en) = '', s.name_en, c.name_en);

INSERT INTO countries (iso2, iso3, name_cs, name_en, is_eu)
SELECT s.iso2, s.iso3, s.name_cs, s.name_en, 0
  FROM tmp_1828_countries s
 WHERE NOT EXISTS (
         SELECT 1 FROM countries c
          WHERE UPPER(TRIM(c.iso2)) = s.iso2
             OR UPPER(TRIM(c.iso3)) = s.iso3
       )
 ORDER BY s.iso2;

